using System.Text;

namespace Agentic.Orchestration.Workflow;

public sealed class WorkflowValidationException : Exception
{
    public WorkflowValidationException(string message) : base(message) { }
}

/// <summary>
/// Explicit DAG of SDLC stages. Validated on creation and on every runtime patch, so a planner
/// can never introduce a cycle or a dangling dependency.
/// </summary>
public sealed class WorkflowGraph
{
    private Dictionary<string, StageDefinition> _stages;
    private List<string> _order;

    private WorkflowGraph(string name, IEnumerable<StageDefinition> stages)
    {
        Name = name;
        _stages = new Dictionary<string, StageDefinition>(StringComparer.Ordinal);
        _order = new List<string>();
        foreach (var stage in stages)
        {
            if (!_stages.TryAdd(stage.Id, stage))
                throw new WorkflowValidationException($"Duplicate stage id '{stage.Id}'.");
            _order.Add(stage.Id);
        }
        Validate(_stages);
    }

    public string Name { get; }

    public IReadOnlyList<StageDefinition> Stages => _order.Select(id => _stages[id]).ToList();

    public StageDefinition this[string id] => _stages[id];

    public bool Contains(string id) => _stages.ContainsKey(id);

    public static WorkflowGraph Create(string name, IEnumerable<StageDefinition> stages) => new(name, stages);

    public IReadOnlyList<string> TopologicalOrder() => TopologicalSort(_stages);

    /// <summary>Groups stages into levels; stages in the same level have no path between them and may run in parallel.</summary>
    public IReadOnlyList<IReadOnlyList<string>> Levels()
    {
        var level = new Dictionary<string, int>();
        foreach (var id in TopologicalOrder())
            level[id] = _stages[id].DependsOn.Count == 0 ? 0 : _stages[id].DependsOn.Max(d => level[d]) + 1;
        return level.GroupBy(kv => kv.Value).OrderBy(g => g.Key)
            .Select(g => (IReadOnlyList<string>)g.Select(kv => kv.Key).OrderBy(id => _order.IndexOf(id)).ToList())
            .ToList();
    }

    public IReadOnlyList<string> DirectDependents(string id) =>
        _order.Where(s => _stages[s].DependsOn.Contains(id)).ToList();

    public IReadOnlySet<string> TransitiveDependents(string id)
    {
        var result = new HashSet<string>(StringComparer.Ordinal);
        var queue = new Queue<string>(DirectDependents(id));
        while (queue.TryDequeue(out var next))
            if (result.Add(next))
                foreach (var d in DirectDependents(next))
                    queue.Enqueue(d);
        return result;
    }

    /// <summary>
    /// Applies a planner's patch atomically: stages previously generated by <paramref name="ownerId"/>
    /// are replaced, new stages are wired into the sync stages, and the result is re-validated.
    /// On any validation error the graph is left unchanged.
    /// </summary>
    public IReadOnlyList<string> ApplyPatch(string ownerId, GraphPatch patch)
    {
        var next = new Dictionary<string, StageDefinition>(_stages, StringComparer.Ordinal);
        var order = new List<string>(_order);

        var removed = next.Values.Where(s => s.GeneratedBy == ownerId).Select(s => s.Id).ToList();
        foreach (var id in removed)
        {
            next.Remove(id);
            order.Remove(id);
        }
        foreach (var id in next.Keys.ToList())
        {
            var stage = next[id];
            if (stage.DependsOn.Any(removed.Contains))
                next[id] = stage with { DependsOn = stage.DependsOn.Where(d => !removed.Contains(d)).ToList() };
        }

        var insertAt = order.IndexOf(ownerId) + 1;
        foreach (var stage in patch.AddStages)
        {
            // Generated stages always depend on their owner, so re-running the owner invalidates them.
            var wired = stage with
            {
                GeneratedBy = ownerId,
                DependsOn = stage.DependsOn.Contains(ownerId) ? stage.DependsOn : stage.DependsOn.Append(ownerId).ToList(),
            };
            if (!next.TryAdd(stage.Id, wired))
                throw new WorkflowValidationException($"Patch from '{ownerId}' adds duplicate stage '{stage.Id}'.");
            order.Insert(insertAt++, stage.Id);
        }

        foreach (var syncId in patch.SyncStages)
        {
            if (!next.TryGetValue(syncId, out var sync))
                throw new WorkflowValidationException($"Patch from '{ownerId}' references unknown sync stage '{syncId}'.");
            next[syncId] = sync with { DependsOn = sync.DependsOn.Union(patch.AddStages.Select(s => s.Id)).ToList() };
        }

        Validate(next);
        _stages = next;
        _order = order;
        return removed;
    }

    public string ToMermaid(IReadOnlyDictionary<string, string>? statusById = null)
    {
        var sb = new StringBuilder("flowchart TD\n");
        foreach (var id in _order)
        {
            var stage = _stages[id];
            var label = statusById is not null && statusById.TryGetValue(id, out var status) ? $"{stage.Name}<br/>{status}" : stage.Name;
            var shape = stage.RequiresApproval ? $"{{{{\"{label}\"}}}}" : $"[\"{label}\"]";
            sb.Append("    ").Append(Sanitize(id)).Append(shape).Append('\n');
        }
        foreach (var id in _order)
            foreach (var dep in _stages[id].DependsOn)
                sb.Append("    ").Append(Sanitize(dep)).Append(" --> ").Append(Sanitize(id)).Append('\n');
        return sb.ToString();
    }

    private static string Sanitize(string id) => new(id.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

    private static void Validate(IReadOnlyDictionary<string, StageDefinition> stages)
    {
        foreach (var stage in stages.Values)
            foreach (var dep in stage.DependsOn)
            {
                if (!stages.ContainsKey(dep))
                    throw new WorkflowValidationException($"Stage '{stage.Id}' depends on unknown stage '{dep}'.");
                if (dep == stage.Id)
                    throw new WorkflowValidationException($"Stage '{stage.Id}' depends on itself.");
            }
        TopologicalSort(stages);
    }

    private static IReadOnlyList<string> TopologicalSort(IReadOnlyDictionary<string, StageDefinition> stages)
    {
        // Kahn's algorithm; leftover nodes mean a cycle.
        var inDegree = stages.Keys.ToDictionary(k => k, k => stages[k].DependsOn.Distinct().Count());
        var ready = new Queue<string>(inDegree.Where(kv => kv.Value == 0).Select(kv => kv.Key).OrderBy(k => k, StringComparer.Ordinal));
        var result = new List<string>();
        while (ready.TryDequeue(out var id))
        {
            result.Add(id);
            foreach (var dependent in stages.Values.Where(s => s.DependsOn.Contains(id)).Select(s => s.Id).OrderBy(k => k, StringComparer.Ordinal))
                if (--inDegree[dependent] == 0)
                    ready.Enqueue(dependent);
        }
        if (result.Count != stages.Count)
        {
            var cyclic = string.Join(", ", inDegree.Where(kv => kv.Value > 0).Select(kv => kv.Key).OrderBy(k => k));
            throw new WorkflowValidationException($"Workflow contains a dependency cycle involving: {cyclic}.");
        }
        return result;
    }
}
